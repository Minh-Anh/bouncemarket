-- Run this in the Supabase SQL editor to create the tables the server uses.
-- It only adds what is missing, so it is safe to run again after an update.

create table if not exists players (
  id text primary key,  -- the random id the player's browser remembers; treat it like a password
  name text not null check (char_length(name) between 1 and 16),
  points numeric not null default 10
);

-- Whether the owner has replaced this player's name and locked it, so they can't change it
-- themselves (see "Moderating names" in the README). Added after the table was first made,
-- so it is added here on its own, for tables made before it existed.
alter table players add column if not exists name_locked boolean not null default false;

-- Names are unique, ignoring capitals, so "Sam" and "sam" can't both exist.
create unique index if not exists players_name_unique on players (lower(name));

-- Makes the leaderboard query (the highest points first) fast.
create index if not exists players_points on players (points desc);

-- Row level security with no policies: only the server's secret key can read or write this
-- table. The public key that browsers could use gets nothing.
alter table players enable row level security;


-- The round log, for analysis. See "The round log" in the README.

-- A small number for every player who has ever bought a share, named or not. The round log
-- uses it in place of the long id, so each logged buy takes a few bytes.
create table if not exists player_keys (
  key integer generated by default as identity primary key,
  id text not null unique  -- the same id as players.id; treat it like a password
);

alter table player_keys enable row level security;

-- One row for every round that at least one player bought in.
create table if not exists rounds (
  id bigint generated by default as identity primary key,
  started_at timestamptz not null unique,  -- when the ball dropped
  commit_id text not null,  -- the version of the code that played the round ("local" when not on Render)
  gravity double precision not null,
  bounce double precision not null,
  start_x double precision not null,  -- where along the top the ball dropped from; the whole path follows from it
  frames integer not null,  -- how many frames the ball took to land, at 60 a second
  close_frame integer not null,  -- the frame betting closed at
  bucket text not null check (bucket in ('left', 'right')),  -- where the ball landed
  format smallint not null,  -- how path and buys are packed: LOG_FORMAT in app.py
  n_buys integer not null,
  path bytea not null,  -- the ball's position at every frame, packed by pack_path() in app.py
  buys bytea not null  -- every buy, in order, packed by pack_buys() in app.py
);

alter table rounds enable row level security;

-- Which pricing and counterparty rules the round was played by (RULES_VERSION in app.py), so
-- analysis.py works out its prices and counterparty buys under the right ones. Rounds logged
-- before it existed were version 1: see prices_v1() and counterparty_v1() in analysis.py.
alter table rounds add column if not exists rules smallint not null default 1;

-- When each broadcast went out to the pages and when each buy was taken, to the microsecond,
-- packed by pack_timing() in app.py. Null for rounds logged before it existed. See "Timing" under
-- "The round log" in the README.
alter table rounds add column if not exists timing bytea;

-- The hidden random turns the ball takes at each pin bounce (see simulate_drop() in app.py): how
-- big they typically are, in radians, and the seed they were drawn from, kept secret until the
-- round was over. With start_x, they give the whole path. Null for rounds played before them,
-- which had no turns.
alter table rounds add column if not exists nudge double precision;
alter table rounds add column if not exists nudge_seed bigint;


-- The best-round card. See "The best-round card" in the README.

-- One row for every round that became a player's best when it was played. A row is never
-- changed or removed when a better round comes along, so old share links keep working: a
-- player's best round now is simply their row with the most profit.
create table if not exists best_rounds (
  share_id text primary key,  -- the short random id in the link, /r/<share_id>
  player text not null,  -- the same id as players.id; treat it like a password, never show it
  username text,  -- the player's name when the round was played, or null for a guest
  round_started_at timestamptz not null,  -- which round: the same as rounds.started_at
  settled_at timestamptz not null,  -- when the ball landed
  outcome text not null check (outcome in ('left', 'right')),  -- where the ball landed
  frames integer not null,  -- how many frames (60 a second) the ball took to land
  close_frame integer not null,  -- the frame trading closed at
  trades jsonb not null,  -- the player's buys, as [[frame, side, price, shares], ...]
  prices jsonb not null,  -- the left side's price over the round, as [[frame, price], ...]
  cost numeric not null,  -- everything the player paid this round, both sides
  payout numeric not null,  -- 1 for each share on the side the ball landed on
  profit numeric not null,  -- payout minus cost
  trajectory jsonb not null  -- what the ball's path follows from: {"start_x", "gravity", "bounce", "nudge", "nudge_seed", "commit_id"} (no nudges before they were added)
);

-- Whether the player has deleted this card from their page. A cleared row no longer counts as
-- their best round, so their next round over 1.00 makes a new card, but its share link still
-- works. Added after the table was first made, so it is added here on its own.
alter table best_rounds add column if not exists cleared boolean not null default false;

-- Makes finding a player's best round fast.
create index if not exists best_rounds_player on best_rounds (player, profit desc);

alter table best_rounds enable row level security;


-- Ask Supabase's web API to read the tables again, so it knows about any column just added
-- straight away. (It usually notices by itself; this makes sure.)
notify pgrst, 'reload schema';
